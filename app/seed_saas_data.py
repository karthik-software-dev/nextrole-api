def seed_database():
    print("==================================================")
    print("Seeding Production-Grade SaaS Data into PostgreSQL")
    print("==================================================")
    init_db()

    with get_db() as session:
        user = seed_default_user(session)
        created_job_map = {}

        # 1. Upsert all 24 high-priority jobs
        for item in JOBS_DATA:
            job_dc = JobDataclass(
                id=item["id"],
                title=item["title"],
                company=item["company"],
                source=item["source"],
                location=item["location"],
                is_remote=item["is_remote"],
                salary_raw=item["salary_raw"],
                description=item["description"],
                discovery_url=item["discovery_url"],
                apply_url=item["apply_url"],
                apply_type=item["apply_type"],
                ats_provider=item["ats_provider"],
                relevance_score=item["relevance_score"],
                matched_skills=item["matched_skills"],
                priority_score=item["priority_score"],
                priority_tier=item["priority_tier"],
                experience_min=item["experience_min"],
                experience_max=item["experience_max"],
                experience_raw=item["experience_raw"],
            )
            job_rec, is_new = JobRepository.upsert_job(session, job_dc)
            job_rec.is_active = True
            created_job_map[item["id"]] = job_rec.id
            status_str = "Created" if is_new else "Updated"
            print(f"[{status_str}] Job #{job_rec.id}: {job_rec.title} @ {item['company']}")

        # 2. Flag target companies
        target_companies = [
            "Razorpay", "Zepto", "Cred", "Swiggy", "Groww", "Cisco",
            "Zoho", "Atlassian", "Urban Company", "PhonePe", "Flipkart", "Postman", "Google"
        ]
        for name in target_companies:
            CompanyRepository.get_or_create_company(session, name, is_target=True)

        session.flush()

        # 3. Seed application tracking entries into CRM
        for app_spec in APPLICATIONS_SEED:
            job_id = created_job_map.get(app_spec["job_id_key"])
            if job_id:
                app_rec = ApplicationRepository.record_application(
                    session=session,
                    user_id=user.id,
                    job_id=job_id,
                    portal_type=app_spec["portal"],
                    notes=app_spec["notes"],
                    initial_status=app_spec["status"],
                )
                print(f"[Application CRM] Seeded {app_spec['status'].upper()} application for Job #{job_id}")

        session.commit()
        print("\n[SUCCESS] Successfully seeded 24 jobs, 14 applications, and target companies into PostgreSQL.")


if __name__ == "__main__":
    seed_database()
