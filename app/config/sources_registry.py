def get_all_sources() -> list[SourceDefinition]:
    """Returns the complete list of 31 verified integrated sources."""
    return list(SOURCES_REGISTRY)


def get_source_by_slug(slug: str) -> SourceDefinition | None:
    """Finds a source definition by slug."""
    for s in SOURCES_REGISTRY:
        if s.slug.lower() == slug.lower():
            return s
    return None
